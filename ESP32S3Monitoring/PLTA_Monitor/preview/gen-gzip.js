const fs = require("fs");
const zlib = require("zlib");
const path = require("path");

const root = path.join(__dirname, "..");

function extract(file, varName) {
  const source = fs.readFileSync(path.join(root, file), "utf8");
  const pattern = new RegExp(
    varName + '\\s*\\[\\]\\s*PROGMEM\\s*=\\s*R"rawliteral\\(([\\s\\S]*?)\\)rawliteral"',
  );
  const match = source.match(pattern);
  if (!match) throw new Error(`Could not extract ${varName} from ${file}`);
  return Buffer.from(match[1], "utf8");
}

const assets = [
  { file: "webpage.h", var: "index_html", name: "index_html_gz" },
  { file: "style.h", var: "style_css", name: "style_css_gz" },
  { file: "app.h", var: "app_js", name: "app_js_gz" },
];

let output = '#pragma once\n';
output += '// AUTO-GENERATED by preview/gen-gzip.js - do not edit by hand.\n';
output += '// Regenerate after editing assets: node preview/gen-gzip.js\n\n';

let rawTotal = 0;
let gzipTotal = 0;

for (const asset of assets) {
  const raw = extract(asset.file, asset.var);
  const gzip = zlib.gzipSync(raw, { level: 9 });
  rawTotal += raw.length;
  gzipTotal += gzip.length;

  output += `// ${asset.var}: ${raw.length} -> ${gzip.length} bytes gzipped\n`;
  output += `const uint8_t ${asset.name}[] PROGMEM = {${Array.from(gzip).join(",")}};\n`;
  output += `const unsigned int ${asset.name}_len = ${gzip.length};\n\n`;
}

fs.writeFileSync(path.join(root, "web_assets_gz.h"), output);
console.log(
  `Wrote web_assets_gz.h (${rawTotal} -> ${gzipTotal} bytes)`
);
